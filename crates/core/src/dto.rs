use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Input payload for a single malware analysis invocation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AnalysisRequest {
    /// File path (or logical identifier) of the sample to analyze.
    pub sample_path: String,
    /// Plugin package name selected for execution.
    pub plugin_name: String,
    /// Additional plugin-specific input payload.
    pub input: Value,
}

/// Normalized output returned by the analysis service.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AnalysisResult {
    /// Echoed sample path used for execution.
    pub sample_path: String,
    /// Plugin name used for the run.
    pub plugin_name: String,
    /// Human-readable summary generated by the plugin/runtime.
    pub summary: String,
    /// Risk score represented as a floating-point value.
    pub risk_score: f64,
    /// Raw plugin output preserved for consumers needing full fidelity.
    pub raw_output: Value,
}
